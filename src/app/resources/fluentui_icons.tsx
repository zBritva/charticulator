function createIcon(Icon: React.ComponentType<React.SVGProps<SVGSVGElement>>, displayName: string) {
    const Wrapped = React.forwardRef<SVGSVGElement, FluentIconsProps>(
        ({ className, primaryFill, ...rest }, ref) => (
            <Icon
                ref={ref}
                fill={primaryFill || "currentColor"}
                className={className}
                {...rest}
                {...IconProps}
            />
        )
    );

    Wrapped.displayName = displayName;
    return Wrapped;
}

